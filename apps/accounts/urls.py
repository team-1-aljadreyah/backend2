"""URL routes for auth, lookups, users, settings, and price tiers under /api/v1/."""
from django.urls import path

from .views import (
    CustomValuesView,
    LoginView,
    LogoutView,
    LookupsView,
    MeDeleteView,
    MePasswordView,
    MePhotoView,
    MeShopRemoveView,
    MeView,
    PriceTierCreateView,
    PriceTierUpdateView,
    RefreshTokenView,
    RegisterView,
    RuleRunsView,
    SettingsUpdateView,
    SetupHealthView,
    SitePublicView,
    SiteUpdateView,
    UserDetailView,
    UserPhotoRemoveView,
    UserProfileView,
    UsersListCreateView,
)

urlpatterns = [
    path("auth/login", LoginView.as_view(), name="auth-login"),
    path("auth/register", RegisterView.as_view(), name="auth-register"),
    path("auth/logout", LogoutView.as_view(), name="auth-logout"),
    path("auth/refresh", RefreshTokenView.as_view(), name="auth-refresh"),
    path("me", MeView.as_view(), name="auth-me"),
    path("me/photo", MePhotoView.as_view(), name="me-photo"),
    path("me/password", MePasswordView.as_view(), name="me-password"),
    path("me/shops/<int:customer_id>/remove", MeShopRemoveView.as_view(), name="me-shop-remove"),
    path("me/delete", MeDeleteView.as_view(), name="me-delete"),
    path("lookups", LookupsView.as_view(), name="lookups"),
    path("users", UsersListCreateView.as_view(), name="users-list-create"),
    path("users/<int:user_id>", UserDetailView.as_view(), name="user-detail"),
    path("users/<int:user_id>/profile", UserProfileView.as_view(), name="user-profile"),
    path("users/<int:user_id>/photo", UserPhotoRemoveView.as_view(), name="user-photo-remove"),
    path("settings", SettingsUpdateView.as_view(), name="settings-update"),
    path("settings/site", SiteUpdateView.as_view(), name="settings-site-update"),
    path("site", SitePublicView.as_view(), name="site-public"),
    path("custom/<str:object_type>/<int:object_id>", CustomValuesView.as_view(), name="custom-values-save"),
    path("setup/rule-runs", RuleRunsView.as_view(), name="setup-rule-runs"),
    path("setup/health", SetupHealthView.as_view(), name="setup-health"),
    path("price-tiers", PriceTierCreateView.as_view(), name="price-tiers-create"),
    path("price-tiers/<int:tier_id>", PriceTierUpdateView.as_view(), name="price-tiers-update"),
]
